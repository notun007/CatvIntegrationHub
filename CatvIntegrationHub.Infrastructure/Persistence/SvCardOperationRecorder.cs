using CatvIntegrationHub.Application.Cards;
using CatvIntegrationHub.Domain.Entities;
using CatvIntegrationHub.Domain.Enums;

namespace CatvIntegrationHub.Infrastructure.Persistence;

internal sealed class SvCardOperationRecorder : ISvCardOperationRecorder
{
    private readonly CasHubDbContext _db;

    public SvCardOperationRecorder(CasHubDbContext db) => _db = db;

    public async Task RecordAsync(string cardId, string? chipId, SvCardStatusEnum status,
        CancellationToken cancellationToken = default)
    {
        if (!Enum.IsDefined(typeof(SvCardStatusEnum), status))
            throw new ArgumentOutOfRangeException(nameof(status));

        _db.SvCards.Add(new SvCard
        {
            CardId = cardId.Trim(),
            ChipId = chipId?.Trim(),
            SvCardStatusId = (short)status,
            CreatedBy = 1
            // Id and CreatedDate are generated by SQL Server. Update fields stay null.
        });
        await _db.SaveChangesAsync(cancellationToken);
    }
}